// Regenerate after rebuilding range scans: node tools/build-range-shapes.mjs
import { writeFile } from 'node:fs/promises';
import { RANGES, LOADERS } from '../src/world/terrain/ranges/index.js';
import { profilesFromJSON, profileUnits } from '../src/world/terrain/TerrainProfile.js';
const shapes = {};
for (const range of RANGES) {
  const units = profileUnits(profilesFromJSON((await LOADERS[range.id]()).default).L2);
  const width = Math.max(2, Math.round(units.length * 0.16));
  let walls = 0, count = 0;
  for (let start = 0; start <= units.length - width; start += Math.max(1, Math.floor(width / 2))) {
    const window = Array.from(units.slice(start, start + width)).sort((a, b) => a - b);
    const low = window[Math.floor((width - 1) * 0.1)];
    const high = window[Math.floor((width - 1) * 0.9)];
    if (low > 0.5 && high - low < 0.25) walls++;
    count++;
  }
  shapes[range.id] = Number((walls / count).toFixed(4));
}
await writeFile(new URL('../src/world/terrain/ranges/shapes.js', import.meta.url),
  '// Generated by tools/build-range-shapes.mjs. Fraction of viewport windows that form high, flat walls.\n'
  + `export const WALL_SHARE = ${JSON.stringify(shapes, null, 2)};\n`);
