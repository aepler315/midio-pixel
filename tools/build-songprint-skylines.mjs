// Bake compact outlines beside the catalog so opening the library never downloads a DEM.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { decodeTerrain } from '../src/world/alpine/TerrainMesh.js';
import { railTile } from '../src/world/alpine/TerrainPackage.js';
import { hashSeed } from '../src/utils/math.js';
import scenes from '../src/world/terrain/sceneCatalogData.js';
import massifs from '../src/world/terrain/massifCatalogData.js';

const base = new URL('../src/assets/range/v2/', import.meta.url);
const output = new URL('../src/world/terrain/songprintSkylines.js', import.meta.url);
const count = 16;
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');

function measure(path, manifestHash, camera) {
  const url = new URL(path, base);
  const bytes = readFileSync(url);
  if (digest(bytes) !== manifestHash) throw new Error('Unpinned terrain: ' + path);
  const manifest = JSON.parse(bytes);
  const payload = readFileSync(new URL(manifest.payload.url, url));
  if (digest(payload) !== manifest.payload.sha256) throw new Error('Unpinned relief: ' + path);
  const { tiles, grid, cells } = decodeTerrain(manifest, gunzipSync(payload));
  const fine = new Float64Array(count * 4).fill(-Infinity);
  const eye = camera?.eyeStartM.map((v, i) => (v + camera.eyeEndM[i]) / 2);
  const target = camera?.targetStartM.map((v, i) => (v + camera.targetEndM[i]) / 2);
  const dx = camera ? target[0] - eye[0] : 0;
  const dz = camera ? target[2] - eye[2] : 0;
  const length = Math.hypot(dx, dz);
  const fov = camera ? Math.tan(camera.fovYDeg * Math.PI / 360) * 16 / 9 : 0;
  for (const tile of tiles.values()) {
    if (!railTile(tile)) continue;
    const step = Math.max(1, 4 / tile.stride);
    for (let v = 0; v < tile.samples; v += step) {
      for (let u = 0; u < tile.samples; u += step) {
        const height = tile.heightsM[v * tile.samples + u];
        if (!Number.isFinite(height)) continue;
        const gx = tile.ix * cells + u * tile.stride;
        let position = gx / (grid.width - 1), level = height;
        if (camera) {
          const x = grid.originM[0] + gx * grid.cellSizeM - eye[0];
          const z = grid.originM[1] + (tile.iz * cells + v * tile.stride) * grid.cellSizeM - eye[2];
          const depth = (x * dx + z * dz) / length;
          if (depth <= 0) continue;
          position = 0.5 + (z * dx - x * dz) / (2 * length * depth * fov);
          level = (height - eye[1]) / depth;
        }
        if (position < 0 || position > 1) continue;
        const bin = Math.min(fine.length - 1, Math.floor(position * fine.length));
        fine[bin] = Math.max(fine[bin], level);
      }
    }
  }
  const outline = Array.from({ length: count }, (_, i) => {
    const within = fine.slice(4 * i, 4 * i + 4).filter(Number.isFinite);
    if (!within.length) throw new Error('Empty skyline bin: ' + path);
    return within.reduce((a, b) => a + b, 0) / within.length;
  });
  const min = Math.min(...outline), span = Math.max(...outline) - min;
  if (!span) throw new Error('Flat skyline: ' + path);
  return outline.map(v => Math.round(255 * (v - min) / span));
}

const lines = ['// Generated by tools/build-songprint-skylines.mjs from pinned elevation packages.'];
for (const [name, records] of [
  ['viewSkylines', scenes.views.filter(v => v.camera && v.terrainManifestUrl)
    .map(v => [v.id, v.terrainManifestUrl, v.terrainManifestSha256, v.camera])],
  ['massifSkylines', massifs.pieces.map(p => [p.manifestSha256, p.manifestUrl, p.manifestSha256, null])],
]) {
  lines.push('export const ' + name + ' = {');
  for (const [key, path, hash, camera] of records) {
    const outline = '[' + measure(path, hash, camera).join(',') + ']';
    const value = camera ? '{ terrain: "' + hash + '", camera: ' + hashSeed(JSON.stringify(camera))
      + ', outline: ' + outline + ' }' : outline;
    lines.push('  ' + JSON.stringify(key) + ': ' + value + ',');
  }
  lines.push('};');
}
const source = lines.join('\n') + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== source) throw new Error('Rebuild the Songprint skyline index');
} else {
  writeFileSync(output, source);
}
