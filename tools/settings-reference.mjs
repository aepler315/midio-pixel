// Generate docs/url-parameters.md from the settings registry.
//   node tools/settings-reference.mjs           write the file
//   node tools/settings-reference.mjs --check   exit 1 when it is stale
// test/settingsReference.test.mjs runs the check, so a new or changed
// setting cannot land without its reference.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  SETTINGS, SECTIONS, LIFECYCLES, RETIRED_PARAMS, FOREIGN_PARAMS, defaultValue, formatUrlValue,
} from '../src/config/settingsRegistry.js';

export const REFERENCE_PATH = fileURLToPath(new URL('../docs/url-parameters.md', import.meta.url));

const cell = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function valuesOf(def) {
  if (def.type === 'enum') return def.options.map(o => `\`${formatUrlValue(def, o.value) || o.value}\``).join(', ');
  if (def.type === 'boolean') return def.parseUrl ? 'see note' : '`1`, `0`';
  if (def.type === 'number') return `${def.min}–${def.max}${def.nullable ? ' (empty: automatic)' : ''}`;
  return def.pattern ? `text matching \`${def.pattern.source}\`` : 'text';
}

function defaultOf(def) {
  const v = defaultValue(def);
  if (v === null) return 'automatic';
  return `\`${def.type === 'boolean' ? (v ? 'on' : 'off') : v}\``;
}

const PERSIST = {
  saved: 'Saved in this browser when changed in Settings; a URL value lasts for the visit',
  url: 'Not saved; kept in the address bar so a reload or shared link reproduces it',
  none: 'Not saved',
};

export function renderReference() {
  const out = [];
  out.push('# URL parameters', '');
  out.push('> Generated by `node tools/settings-reference.mjs` from',
    '> `src/config/settingsRegistry.js`. Do not edit by hand; `npm test` fails',
    '> when this file is stale. Architecture: [settings](settings.md).', '');
  out.push('Every parameter below is an optional override of a registered setting.',
    'Precedence is **URL → saved preference → default**. A URL value applies to',
    'the visit and is shown in Settings with a *From page address* badge; it is',
    'not saved unless you choose **Save as my settings**. An invalid value is',
    'rejected and reported in Settings → Diagnostics (some parameters keep a',
    'historical fallback, noted below). Unknown parameters are ignored and listed',
    'in Diagnostics. **Copy share link** builds a URL with only the settings that',
    'differ from their defaults.', '');
  out.push('Lifecycle: when a change reaches a running page.', '');
  for (const [id, lc] of Object.entries(LIFECYCLES)) out.push(`- **${lc.short}** (\`${id}\`): ${lc.label}.`);
  out.push('');
  const groups = [...SECTIONS.map(s => ({ id: s.id, label: s.label })), { id: null, label: 'Automation (URL only)' }];
  for (const group of groups) {
    const defs = SETTINGS.filter(d => d.url && (d.section ?? null) === group.id);
    if (!defs.length) continue;
    out.push(`## ${group.label}`, '');
    out.push('| Parameter | Setting | Values | Default | Lifecycle | In Settings | Persistence |');
    out.push('| --- | --- | --- | --- | --- | --- | --- |');
    for (const def of defs) {
      const shown = def.ui === false ? 'no (URL only)' : def.tier === 'basic' ? 'yes' : `yes (${def.tier})`;
      out.push(`| \`${def.url}\` | ${cell(def.label)} | ${cell(valuesOf(def))} | ${defaultOf(def)} | ${LIFECYCLES[def.lifecycle].short} | ${shown} | ${cell(PERSIST[def.persist])} |`);
    }
    out.push('');
    for (const def of defs) {
      const notes = [def.description];
      if (def.urlNote) notes.push(`URL rule: ${def.urlNote}`);
      if (def.requires?.length) notes.push(`Inactive unless: ${def.requires.map(r => r.reason).join(' ')}`);
      out.push(`- \`${def.url}\` — ${notes.join(' ')}`);
    }
    out.push('');
  }
  out.push('## Retired or ignored parameters', '');
  out.push('Accepted without error, reported as ignored in Diagnostics.', '');
  for (const [name, reason] of Object.entries(RETIRED_PARAMS)) out.push(`- \`${name}\` — ${reason}`);
  for (const [name, reason] of Object.entries(FOREIGN_PARAMS)) out.push(`- \`${name}\` — ${reason}`);
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const text = renderReference();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(REFERENCE_PATH) ? fs.readFileSync(REFERENCE_PATH, 'utf8') : '';
    if (current !== text) { console.error('docs/url-parameters.md is stale: run node tools/settings-reference.mjs'); process.exit(1); }
    console.log('docs/url-parameters.md is current');
  } else {
    fs.writeFileSync(REFERENCE_PATH, text);
    console.log(`wrote ${REFERENCE_PATH}`);
  }
}
