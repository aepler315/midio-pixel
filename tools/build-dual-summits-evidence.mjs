// Offline only: derive broad role evidence from explicitly supplied aligned
// PCM WAV exports. No audio or machine-specific path is embedded in the asset.
// node tools/build-dual-summits-evidence.mjs --mix MIX.wav --clean CLEAN.wav
//   --distortion DIST.wav --other REST.wav --out src/assets/performance/ds182.js
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

const SCALE = 100000;
const percentile = (values, q) => values.slice().sort((a, b) => a - b)[Math.floor((values.length - 1) * q)] || 0;

export function summarizePcmWave(bytes, stepMs = 500) {
  if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WAVE') throw Error('Expected a RIFF WAV');
  let format, data;
  for (let at = 12; at + 8 <= bytes.length;) {
    const name = bytes.toString('ascii', at, at + 4), size = bytes.readUInt32LE(at + 4), start = at + 8;
    if (start + size > bytes.length) throw Error('Truncated WAV chunk');
    if (name === 'fmt ') format = { encoding: bytes.readUInt16LE(start), channels: bytes.readUInt16LE(start + 2),
      sampleRate: bytes.readUInt32LE(start + 4), align: bytes.readUInt16LE(start + 12), bits: bytes.readUInt16LE(start + 14) };
    if (name === 'data') data = bytes.subarray(start, start + size);
    at = start + size + (size % 2);
  }
  if (!format || !data || format.encoding !== 1 || ![16, 24, 32].includes(format.bits)
    || ![1, 2].includes(format.channels) || format.align !== format.channels * format.bits / 8) throw Error('Expected mono/stereo integer PCM WAV');
  const { sampleRate, channels, bits, align } = format, width = bits / 8;
  const frames = data.length / align, perStep = Math.round(sampleRate * stepMs / 1000), rms = [];
  if (!Number.isInteger(frames) || !perStep) throw Error('Invalid WAV sample count or step');
  for (let start = 0; start < frames; start += perStep) {
    let squares = 0;
    const end = Math.min(frames, start + perStep);
    for (let i = start * channels; i < end * channels; i++) {
      const value = data.readIntLE(i * width, width) / (2 ** (bits - 1));
      squares += value * value;
    }
    rms.push(Math.round(SCALE * Math.sqrt(squares / ((end - start) * channels))));
  }
  const p95 = percentile(rms, .95), first = rms.findIndex(v => v > Math.max(10, p95 * .12));
  return { durationMs: +((frames / sampleRate) * 1000).toFixed(3), sampleRate, channels, frames,
    bits, p95, firstActiveWindowMs: first < 0 ? null : first * stepMs, rms };
}

export async function buildDualSummitsEvidence(files, out) {
  const sources = {}, tracks = {}, stepMs = 500;
  let canonical = null;
  for (const role of ['mix', 'clean', 'distortion', 'other']) {
    const bytes = await fs.readFile(files[role]), result = summarizePcmWave(bytes, stepMs);
    canonical ||= result;
    if (result.frames !== canonical.frames || result.sampleRate !== canonical.sampleRate || result.channels !== canonical.channels) throw Error('Stem exports must match the mix sample count, rate and channels');
    const { rms, p95, firstActiveWindowMs, ...audio } = result;
    sources[role] = { fileName: path.basename(files[role]), sha256: createHash('sha256').update(bytes).digest('hex'), ...audio };
    tracks[role] = { p95, firstActiveWindowMs, rms };
  }
  const evidence = { version: 1, id: 'ds182', signature: 'dual-summits', durationMs: canonical.durationMs,
    stepMs, rmsScale: 1 / SCALE, method: 'RMS over non-overlapping 500ms stereo PCM windows; physical group power shares; causal 4s response',
    roleProvenance: { clean: 'clean guitar export group', distortion: 'distorted guitar export group', other: 'combined piano, bass, drums and remaining parts; not separated' },
    sources, tracks };
  await fs.mkdir(path.dirname(out), { recursive: true });
  await fs.writeFile(out, '// Generated by tools/build-dual-summits-evidence.mjs from local PCM exports.\n// Compact measurements only; audio remains private.\nexport const DS182_EVIDENCE = ' + JSON.stringify(evidence) + ';\n');
  return evidence;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2), values = {};
  for (let i = 0; i < args.length; i += 2) values[args[i].replace(/^--/, '')] = args[i + 1];
  if (!['mix', 'clean', 'distortion', 'other', 'out'].every(k => values[k])) throw Error('Supply --mix --clean --distortion --other --out');
  const evidence = await buildDualSummitsEvidence(values, values.out);
  console.log(`Saved ${evidence.durationMs}ms measured stem evidence to ${values.out}`);
}
